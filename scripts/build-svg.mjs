// Turns the FG1000 Inkscape SVG into src/pfd-svg.ts: editor metadata stripped, rotation centers kept as
// data-tcx / data-tcy (FlightGear rotates elements around their bounding box center plus this offset).
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../src/PFDInstruments.svg", import.meta.url), "utf8");

const svg = src
  .replace(/<\?xml[^>]*\?>/, "")
  .replace(/<!--[\s\S]*?-->/g, "")
  .replace(/<sodipodi:namedview[\s\S]*?(\/>|<\/sodipodi:namedview>)/, "")
  .replace(/<metadata[\s\S]*?<\/metadata>/, "")
  .replace(/inkscape:transform-center-x=/g, "data-tcx=")
  .replace(/inkscape:transform-center-y=/g, "data-tcy=")
  .replace(/\s(inkscape|sodipodi):[\w-]+="[^"]*"/g, "")
  .replace(/\sxmlns:(inkscape|sodipodi|dc|cc|rdf)="[^"]*"/g, "")
  .replace(/-inkscape-font-specification:[^;"]*;?/g, "")
  .replace(/\n\s*/g, "\n")
  .trim();

writeFileSync(
  new URL("../src/pfd-svg.ts", import.meta.url),
  `// Generated by scripts/build-svg.mjs from PFDInstruments.svg (FlightGear FG1000, GPL-2.0-or-later). Do not edit.\nconst svg: string = ${JSON.stringify(svg)};\nexport default svg;\n`,
);
console.log(`pfd-svg.ts: ${src.length} -> ${svg.length} bytes`);
