// Turns the FG1000 Inkscape SVGs in src/fg1000/ into src/svg/<name>.ts: the markup inside the root <svg>, with editor
// metadata stripped and rotation centers kept as data-tcx / data-tcy (FlightGear rotates elements around their
// bounding box center plus this offset). Fonts the browser may not have get a generic fallback.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const FILES = {
  pfd: "PFDInstruments.svg",
  "surround-pfd": "SurroundPFD.svg",
  "surround-mfd": "Surround.svg",
  eis: "EIS.svg",
  "nav-map": "NavigationMap.svg",
  bezel: "fascia.svg",
  "nrst-pfd": "NearestAirportsPFD.svg",
  "nrst-info-pfd": "NearestAirportsInfoPFD.svg",
  "fpl-pfd": "FlightPlanPFD.svg",
};
// The MFD pages, in one module (src/svg/mfd-pages.ts): name to markup, each in a hidden group with id Page-<name>.
const MFD_PAGES = ["NearestAirports", "NearestVOR", "NearestNDB", "NearestIntersections", "NearestFrequencies", "AirportInfo",
  "VORInfo", "NDBInfo", "IntersectionInfo", "TrafficMap", "Checklist", "DirectTo", "ActiveFlightPlanNarrow", "WaypointEntry"];

const font = (family) => {
  const f = family.trim();
  if (/^(Free)?Sans$/.test(f)) return "sans-serif";
  if (/^(Free|'Ubuntu )Mono'?$/.test(f)) return `${f},monospace`;
  if (/sans-serif|monospace/.test(f)) return f;
  return `${f},${/Narrow|Condensed/.test(f) ? "'Arial Narrow'," : ""}sans-serif`;
};

const clean = (src) =>
  src
    .replace(/\r\n/g, "\n") // a Windows checkout
    .replace(/<\?xml[^>]*\?>/, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<sodipodi:namedview[\s\S]*?<\/sodipodi:namedview>|<sodipodi:namedview[^>]*\/>/, "")
    .replace(/<metadata[\s\S]*?<\/metadata>/, "")
    .replace(/inkscape:transform-center-x=/g, "data-tcx=")
    .replace(/inkscape:transform-center-y=/g, "data-tcy=")
    .replace(/\s(inkscape|sodipodi):[\w-]+="[^"]*"/g, "")
    .replace(/-inkscape-font-specification:[^;"]*;?/g, "")
    .replace(/font-family:([^;"]+)/g, (_, f) => `font-family:${font(f)}`)
    .replace(/\n\s*/g, "\n")
    .trim()
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .trim();

const read = (file) => readFileSync(new URL(`../src/fg1000/${file}`, import.meta.url), "utf8");
const write = (name, from, type, value) =>
  writeFileSync(
    new URL(`../src/svg/${name}.ts`, import.meta.url),
    `// Generated by scripts/build-svg.mjs from ${from} (FlightGear FG1000, GPL-2.0-or-later). Do not edit.\nconst svg: ${type} = ${JSON.stringify(value)};\nexport default svg;\n`,
  );

mkdirSync(new URL("../src/svg/", import.meta.url), { recursive: true });
for (const [name, file] of Object.entries(FILES)) {
  const src = read(file);
  const svg = clean(src);
  write(name, file, "string", svg);
  console.log(`${name}.ts: ${src.length} -> ${svg.length} bytes`);
}
const pages = Object.fromEntries(MFD_PAGES.map((n) => [n, `<g id="Page-${n}" style="display:none">${clean(read(`${n}.svg`))}</g>`]));
write("mfd-pages", "MFDPages/*.svg", "Record<string, string>", pages);
console.log(`mfd-pages.ts: ${MFD_PAGES.length} pages`);

// The display font (README "Font"): Saira Semi Condensed Medium, unmodified, as a data URI so the package needs no asset
// handling from the site's bundler.
const ttf = readFileSync(new URL("../src/fonts/SairaSemiCondensed-Medium.ttf", import.meta.url)).toString("base64");
writeFileSync(
  new URL("../src/svg/font.ts", import.meta.url),
  `// Generated by scripts/build-svg.mjs from src/fonts/SairaSemiCondensed-Medium.ttf (SIL Open Font License 1.1, src/fonts/OFL.txt). Do not edit.\nconst font = "data:font/ttf;base64,${ttf}";\nexport default font;\n`,
);
console.log(`font.ts: ${ttf.length} bytes`);
