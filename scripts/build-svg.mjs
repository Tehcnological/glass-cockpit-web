// Turns the FG1000 Inkscape SVGs in src/fg1000/ into src/svg/<name>.ts: the markup inside the root <svg>, with editor
// metadata stripped and rotation centers kept as data-tcx / data-tcy (FlightGear rotates elements around their
// bounding box center plus this offset). Fonts the browser may not have get a generic fallback.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const FILES = {
  pfd: "PFDInstruments.svg",
  "surround-pfd": "SurroundPFD.svg",
  "surround-mfd": "Surround.svg",
  eis: "EIS.svg",
  "nav-map": "NavigationMap.svg",
  bezel: "fascia.svg",
  "nrst-pfd": "NearestAirportsPFD.svg",
  "nrst-info-pfd": "NearestAirportsInfoPFD.svg",
};

const font = (family) => {
  const f = family.trim();
  if (/^(Free)?Sans$/.test(f)) return "sans-serif";
  if (/^(Free|'Ubuntu )Mono'?$/.test(f)) return `${f},monospace`;
  if (/sans-serif|monospace/.test(f)) return f;
  return `${f},${/Narrow|Condensed/.test(f) ? "'Arial Narrow'," : ""}sans-serif`;
};

mkdirSync(new URL("../src/svg/", import.meta.url), { recursive: true });
for (const [name, file] of Object.entries(FILES)) {
  const src = readFileSync(new URL(`../src/fg1000/${file}`, import.meta.url), "utf8");
  const svg = src
    .replace(/<\?xml[^>]*\?>/, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<sodipodi:namedview[\s\S]*?(\/>|<\/sodipodi:namedview>)/, "")
    .replace(/<metadata[\s\S]*?<\/metadata>/, "")
    .replace(/inkscape:transform-center-x=/g, "data-tcx=")
    .replace(/inkscape:transform-center-y=/g, "data-tcy=")
    .replace(/\s(inkscape|sodipodi):[\w-]+="[^"]*"/g, "")
    .replace(/-inkscape-font-specification:[^;"]*;?/g, "")
    .replace(/font-family:([^;"]+)/g, (_, f) => `font-family:${font(f)}`)
    .replace(/\n\s*/g, "\n")
    .trim()
    .replace(/^<svg[^>]*>/, "")
    .replace(/<\/svg>$/, "")
    .trim();
  writeFileSync(
    new URL(`../src/svg/${name}.ts`, import.meta.url),
    `// Generated by scripts/build-svg.mjs from ${file} (FlightGear FG1000, GPL-2.0-or-later). Do not edit.\nconst svg: string = ${JSON.stringify(svg)};\nexport default svg;\n`,
  );
  console.log(`${name}.ts: ${src.length} -> ${svg.length} bytes`);
}
